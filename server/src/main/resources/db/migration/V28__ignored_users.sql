  `user_id` int(11) NOT NULL,
  `ignored_user_id` int(11) NOT NULL,
  `created_at` datetime(3) NOT NULL DEFAULT current_timestamp(3),
  PRIMARY KEY (`user_id`, `ignored_user_id`),
  KEY `user_id_created_at` (`user_id`, `created_at`),
  KEY `ignored_user_id` (`ignored_user_id`),
  CONSTRAINT `users_ignores_ibfk_1` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `users_ignores_ibfk_2` FOREIGN KEY (`ignored_user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_520_ci;

