-- =========================================================================
-- V31: tabelas do CMS (habbo-cms) para o Minimail, o "e-mail" entre amigos do Habbo de 2009–2012
--
-- cms_minimail_messages: uma mensagem (assunto + corpo em Markdown restrito, que o CMS renderiza com lista branca).
--   staff = 1: mensagem da equipe (selo de staff, sem resposta; campanha para o hotel todo = 1 mensagem e N
--   destinatários). sender_deleted_at: o remetente apagou a cópia de "Enviadas".
-- cms_minimail_recipients: a cópia de cada destinatário (Entrada/Lixeira). trashed_at = na lixeira (o CMS apaga a
--   linha sozinho depois de 30 dias); apagar da lixeira apaga a linha na hora. A mensagem some quando não sobra
--   destinatário e o remetente também a apagou.
-- Os horários são gravados pelo CMS (UTC).
-- cms_minimail_reports: "Denunciar" (o motivo do fim do Minimail em 2012 foi a falta de moderação); a equipe vê a
--   denúncia e a mensagem no CMS. Uma mensagem com denúncia aberta não é apagada pela limpeza.
-- Mais os headers do aviso do Minimail no jogo (secao 4).
-- Idempotente.
-- =========================================================================

CREATE TABLE IF NOT EXISTS `cms_minimail_messages` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `sender_id` int(11) NOT NULL,
  `subject` varchar(150) NOT NULL DEFAULT '',
  `body` text NOT NULL,
  `staff` tinyint(1) NOT NULL DEFAULT 0,
  `reply_to` int(11) DEFAULT NULL,
  `created_at` datetime NOT NULL DEFAULT current_timestamp(),
  `sender_deleted_at` datetime DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `sender_id` (`sender_id`, `created_at`),
  KEY `reply_to` (`reply_to`),
  CONSTRAINT `cms_minimail_messages_ibfk_1` FOREIGN KEY (`sender_id`) REFERENCES `users` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `cms_minimail_messages_ibfk_2` FOREIGN KEY (`reply_to`) REFERENCES `cms_minimail_messages` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_520_ci;

CREATE TABLE IF NOT EXISTS `cms_minimail_recipients` (
  `message_id` int(11) NOT NULL,
  `user_id` int(11) NOT NULL,
  `read_at` datetime DEFAULT NULL,
  `trashed_at` datetime DEFAULT NULL,
  PRIMARY KEY (`message_id`, `user_id`),
  KEY `user_folder` (`user_id`, `trashed_at`),
  KEY `trashed_at` (`trashed_at`),
  CONSTRAINT `cms_minimail_recipients_ibfk_1` FOREIGN KEY (`message_id`) REFERENCES `cms_minimail_messages` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `cms_minimail_recipients_ibfk_2` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_520_ci;

CREATE TABLE IF NOT EXISTS `cms_minimail_reports` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `message_id` int(11) NOT NULL,
  `reporter_id` int(11) NOT NULL,
  `reason` varchar(255) NOT NULL DEFAULT '',
  `created_at` datetime NOT NULL DEFAULT current_timestamp(),
  `resolved_at` datetime DEFAULT NULL,
  `resolved_by` int(11) DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `message_reporter` (`message_id`, `reporter_id`),
  KEY `open_reports` (`resolved_at`, `created_at`),
  CONSTRAINT `cms_minimail_reports_ibfk_1` FOREIGN KEY (`message_id`) REFERENCES `cms_minimail_messages` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `cms_minimail_reports_ibfk_2` FOREIGN KEY (`reporter_id`) REFERENCES `users` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_520_ci;

